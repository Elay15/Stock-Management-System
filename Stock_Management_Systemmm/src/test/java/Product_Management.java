    private void loadProducts() {
    DefaultTableModel model = (DefaultTableModel) Product_tbl.getModel();

    model.setRowCount(0);

    String sql = "SELECT product_id, product_name, unit, current_stock, minimum_stock, selling_price "
               + "FROM products WHERE is_active = 1 ORDER BY product_id";

    try (
        Connection connection = DatabaseConnection.getConnection();
        PreparedStatement statement = connection.prepareStatement(sql);
        ResultSet result = statement.executeQuery()
    ) {

        while (result.next()) {
            model.addRow(new Object[]{
                result.getInt("product_id"),
                result.getString("product_name"),
                result.getString("unit"),
                result.getInt("current_stock"),
                result.getInt("minimum_stock"),
                result.getDouble("selling_price")
            });
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Failed to load products:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}
    
