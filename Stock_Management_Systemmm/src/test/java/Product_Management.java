    private void UpdateProduct_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateProduct_btnActionPerformed
        int selectedRow = Product_tbl.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(
                this,
                "Please select a product from the table.",
                "No Product Selected",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String productName = ProductName_txt.getText().trim();
        String unit = Unit_txt.getText().trim();
        String minimumStockText = MinimumStock_txt.getText().trim();
        String sellingPriceText = SellingPrice_txt.getText().trim();

        if (productName.isEmpty() || unit.isEmpty() || minimumStockText.isEmpty() || sellingPriceText.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Please fill in the required fields.",
                "Incomplete Information",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        try {
            int productId = Integer.parseInt(
                Product_tbl.getValueAt(selectedRow, 0).toString()
            );

            int minimumStock = Integer.parseInt(minimumStockText);
            double sellingPrice = Double.parseDouble(sellingPriceText);

            if (minimumStock < 0) {
                JOptionPane.showMessageDialog(
                    this,
                    "Minimum stock cannot be negative.",
                    "Invalid Input",
                    JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            String sql = "UPDATE products "
            + "SET product_name = ?, unit = ?, minimum_stock = ?, selling_price = ? "
            + "WHERE product_id = ?";

            try (
                Connection connection = DatabaseConnection.getConnection();
                PreparedStatement statement = connection.prepareStatement(sql)
            ) {
                statement.setString(1, productName);
                statement.setString(2, unit);
                statement.setInt(3, minimumStock);
                statement.setDouble(4, sellingPrice);
                statement.setInt(5, productId);

                statement.executeUpdate();
            }

            JOptionPane.showMessageDialog(
                this,
                "Product updated successfully!"
            );

            clearFields();
            loadProducts();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                this,
                "Minimum stock must be a whole number.",
                "Invalid Input",
                JOptionPane.WARNING_MESSAGE
            );

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                this,
                "Failed to update product:\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_UpdateProduct_btnActionPerformed

    private void DeleteProduct_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteProduct_btnActionPerformed
        int selectedRow = Product_tbl.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(
                this,
                "Please select a product from the table.",
                "No Product Selected",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        int productId = Integer.parseInt(
            Product_tbl.getValueAt(selectedRow, 0).toString()
        );

        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this product?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        String sql = "UPDATE products SET is_active = 0 WHERE product_id = ?";

        try (
            Connection connection = DatabaseConnection.getConnection();
            PreparedStatement statement = connection.prepareStatement(sql)
        ) {
            statement.setInt(1, productId);
            statement.executeUpdate();

            JOptionPane.showMessageDialog(
                this,
                "Product deleted successfully!"
            );

            clearFields();
            loadProducts();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                this,
                "Failed to delete product:\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_DeleteProduct_btnActionPerformed

    private void AddProduct_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddProduct_btnActionPerformed

        int selectedRow = Product_tbl.getSelectedRow();

        if (selectedRow != -1) {
            JOptionPane.showMessageDialog(
                this,
                "A product is currently selected. Please clear the fields before adding a new product.",
                "Product Selected",
                JOptionPane.WARNING_MESSAGE
            );
            clearFields();
            return;
        }

        String productName = ProductName_txt.getText().trim();
        String unit = Unit_txt.getText().trim();
        String currentStockText = CurrentStock_txt.getText().trim();
        String minimumStockText = MinimumStock_txt.getText().trim();
        String sellingPriceText = SellingPrice_txt.getText().trim();

        if (productName.isEmpty() || unit.isEmpty()
            || currentStockText.isEmpty() || minimumStockText.isEmpty()
            || sellingPriceText.isEmpty()) {

            JOptionPane.showMessageDialog(
                this,
                "Please fill in all fields.",
                "Incomplete Information",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        try {
            int currentStock = Integer.parseInt(currentStockText);
            int minimumStock = Integer.parseInt(minimumStockText);
            double sellingPrice = Double.parseDouble(sellingPriceText);

            if (currentStock < 0 || minimumStock < 0) {
                JOptionPane.showMessageDialog(
                    this,
                    "Stock values cannot be negative.",
                    "Invalid Input",
                    JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            String sql = "INSERT INTO products "
            + "(product_name, unit, current_stock, minimum_stock, selling_price) "
            + "VALUES (?, ?, ?, ?, ?)";

            try (
                Connection connection = DatabaseConnection.getConnection();
                PreparedStatement statement = connection.prepareStatement(sql)
            ) {
                statement.setString(1, productName);
                statement.setString(2, unit);
                statement.setInt(3, currentStock);
                statement.setInt(4, minimumStock);
                statement.setDouble(5,sellingPrice);

                statement.executeUpdate();
            }

            JOptionPane.showMessageDialog(
                this,
                "Product added successfully!"
            );

            clearFields();
            loadProducts();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                this,
                "Stock and minimum stock must be whole numbers, and selling price must be a valid number.",
                "Invalid Input",
                JOptionPane.WARNING_MESSAGE
            );

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                this,
                "Failed to add product:\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_AddProduct_btnActionPerformed

