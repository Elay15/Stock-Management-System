    private void loadProducts() {
    Product_cmb.removeAllItems();

    String sql = "SELECT product_id, product_name FROM products WHERE is_active = 1 ORDER BY product_name";

    try (
        Connection connection = DatabaseConnection.getConnection();
        PreparedStatement statement = connection.prepareStatement(sql);
        ResultSet result = statement.executeQuery()
    ) {

        while (result.next()) {
            Product_cmb.addItem(
                result.getInt("product_id") + " - " + result.getString("product_name")
            );
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Failed to load products:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}
    
    
private void loadSelectedProduct() {
    if (Product_cmb.getSelectedItem() == null) {
        CurrentStock_txt.setText("");
        return;
    }

    String selectedItem = Product_cmb.getSelectedItem().toString();
    int productId = Integer.parseInt(selectedItem.split(" - ")[0]);

    String sql = "SELECT current_stock FROM products WHERE product_id = ?";

    try (
        Connection connection = DatabaseConnection.getConnection();
        PreparedStatement statement = connection.prepareStatement(sql)
    ) {
        statement.setInt(1, productId);

        try (ResultSet result = statement.executeQuery()) {
            if (result.next()) {
                CurrentStock_txt.setText(
                    String.valueOf(result.getInt("current_stock"))
                );
            } else {
                CurrentStock_txt.setText("");
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Failed to load current stock:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}

    
    
    
    private void loadTransactionHistory() {
     javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel) History_tbl.getModel();

    model.setRowCount(0);

    String sql =
        "SELECT st.transaction_id, p.product_name, st.quantity, " +
        "st.reason, st.transaction_type, st.total_amount, st.transaction_date " +
        "FROM stock_transactions st " +
        "JOIN products p ON st.product_id = p.product_id " +
        "ORDER BY st.transaction_date DESC";

    try (
        Connection connection = DatabaseConnection.getConnection();
        PreparedStatement statement = connection.prepareStatement(sql);
        ResultSet result = statement.executeQuery()
    ) {
        while (result.next()) {
            model.addRow(new Object[] {
                result.getInt("transaction_id"),
                result.getString("product_name"),
                result.getInt("quantity"),
                result.getString("reason"),
                result.getString("transaction_type"),
                result.getDouble("total_amount"),
                result.getTimestamp("transaction_date")
            });
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Failed to load transaction history:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
    }
