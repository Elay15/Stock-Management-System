    private void DeleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteBtnActionPerformed
        int selectedRow = History_tbl.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(
                this,
                "Please select a transaction to delete.",
                "No Selection",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        int transactionId = (int) History_tbl.getValueAt(selectedRow, 0);

        int confirm = JOptionPane.showConfirmDialog(
            this,
           
"Are you sure you want to delete this transaction?\n\n"
+ "WARNING: This only deletes the history record.\n"
+ "It will NOT restore or change the product's stock.",
"Confirm Delete",
JOptionPane.YES_NO_OPTION,
JOptionPane.WARNING_MESSAGE       
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        String sql = "DELETE FROM stock_transactions WHERE transaction_id = ?";

        try (
            Connection connection = DatabaseConnection.getConnection();
            PreparedStatement statement = connection.prepareStatement(sql)
        ) {
            statement.setInt(1, transactionId);

            statement.executeUpdate();

            JOptionPane.showMessageDialog(
                this,
                "Transaction deleted successfully.",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
            );
            loadTransactionHistory();



        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                this,
                "Failed to delete transaction:\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_DeleteBtnActionPerformed

