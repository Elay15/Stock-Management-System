    private void SearchBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SearchBtnActionPerformed
        String search = SearchProduct_txt.getText().trim();

        DefaultTableModel model = (DefaultTableModel) ProductStock_tbl.getModel();
        model.setRowCount(0);

        String sql = "SELECT product_id, product_name, unit, current_stock, minimum_stock "
        + "FROM products "
        + "WHERE is_active = 1 "
        + "AND product_name LIKE ? "
        + "ORDER BY product_id";

        try (
            Connection connection = DatabaseConnection.getConnection();
            PreparedStatement statement = connection.prepareStatement(sql)
        ) {
            statement.setString(1, "%" + search + "%");

            try (ResultSet result = statement.executeQuery()) {

                while (result.next()) {
                    int productId = result.getInt("product_id");
                    String productName = result.getString("product_name");
                    String unit = result.getString("unit");
                    int currentStock = result.getInt("current_stock");
                    int minimumStock = result.getInt("minimum_stock");

                    String status;

                    if (currentStock == 0) {
                        status = "OUT OF STOCK";
                    } else if (currentStock <= minimumStock) {
                        status = "LOW";
                    } else {
                        status = "NORMAL";
                    }

                    model.addRow(new Object[]{
                        productId,
                        productName,
                        unit,
                        currentStock,
                        minimumStock,
                        status
                    });
                }
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                this,
                "Error searching products:\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_SearchBtnActionPerformed

