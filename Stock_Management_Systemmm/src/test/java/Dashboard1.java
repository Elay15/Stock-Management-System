    private void loadDashboard() {
    DefaultTableModel model = (DefaultTableModel) ProductStock_tbl.getModel();

    model.setRowCount(0);

    int totalProducts = 0;
    int lowStock = 0;
    int outOfStock = 0;
    double totalSales = 0.00;

    String sql = "SELECT product_id, product_name, unit, current_stock, minimum_stock "
               + "FROM products WHERE is_active = 1 ORDER BY product_id";
    
    String salesSql = "SELECT COALESCE(SUM(total_amount), 0) AS total_sales "
                + "FROM stock_transactions "
                + "WHERE transaction_type = 'DEDUCT' AND reason = 'Sold'";

    try (
        Connection connection = DatabaseConnection.getConnection();
        PreparedStatement statement = connection.prepareStatement(sql);
        ResultSet result = statement.executeQuery()
    ) {

        while (result.next()) {
            int productId = result.getInt("product_id");
            String productName = result.getString("product_name");
            String unit = result.getString("unit");
            int currentStock = result.getInt("current_stock");
            int minimumStock = result.getInt("minimum_stock");

            String status;

            if (currentStock == 0) {
                status = "OUT OF STOCK";
                outOfStock++;
            } else if (currentStock <= minimumStock) {
                status = "LOW";
                lowStock++;
            } else {
                status = "NORMAL";
            }

            model.addRow(new Object[]{
                productId,
                productName,
                unit,
                currentStock,
                minimumStock,
                status
            });

            totalProducts++;
        }

        TotalProducts_lbl.setText(String.valueOf(totalProducts));
        LowStocks_lbl.setText(String.valueOf(lowStock));
        OutOfStocks_lbl.setText(String.valueOf(outOfStock));
        
        try (PreparedStatement salesStatement = connection.prepareStatement(salesSql);
        ResultSet salesResult = salesStatement.executeQuery()) {

        if (salesResult.next()) {
        totalSales = salesResult.getDouble("total_sales");
    }
}

TotalSales_lbl.setText(String.format("₱%.2f", totalSales));

    } catch (SQLException e) {
        e.printStackTrace();
    }
}
