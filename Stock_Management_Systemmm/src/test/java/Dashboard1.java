    private void BtnOutOfStocksActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnOutOfStocksActionPerformed
        String sql = "SELECT product_name, current_stock, minimum_stock "
        + "FROM products "
        + "WHERE is_active = 1 "
        + "AND current_stock = 0 "
        + "ORDER BY product_name";

        StringBuilder message = new StringBuilder();

        try (
            Connection connection = DatabaseConnection.getConnection();
            PreparedStatement statement = connection.prepareStatement(sql);
            ResultSet result = statement.executeQuery()
        ) {
            while (result.next()) {
                message.append(result.getString("product_name"))
                .append(" — Current: ")
                .append(result.getInt("current_stock"))
                .append(" | Minimum: ")
                .append(result.getInt("minimum_stock"))
                .append("\n");
            }

            if (message.length() == 0) {
                message.append("No out-of-stock products.");
            }

            JOptionPane.showMessageDialog(
                this,
                message.toString(),
                "OUT OF STOCK PRODUCTS",
                JOptionPane.ERROR_MESSAGE
            );

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                this,
                "Error loading out-of-stock products:\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_BtnOutOfStocksActionPerformed

